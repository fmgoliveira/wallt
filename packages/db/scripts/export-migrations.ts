// Turns drizzle-kit output (migrations/*.sql) into src/migrations.generated.ts so the same
// migrations can be applied on device (expo-sqlite, async) and on the server (better-sqlite3).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const journal = JSON.parse(readFileSync(join(root, "migrations/meta/_journal.json"), "utf8")) as {
  entries: { idx: number; tag: string }[];
};

const migrations = journal.entries
  .sort((a, b) => a.idx - b.idx)
  .map(({ tag }) => ({
    tag,
    statements: readFileSync(join(root, "migrations", `${tag}.sql`), "utf8")
      .split("--> statement-breakpoint")
      .map((s) => s.trim())
      .filter(Boolean),
  }));

const out = `// GENERATED by scripts/export-migrations.ts — do not edit. Run \`pnpm --filter @wallt/db db:generate\`.
export const migrations: readonly { tag: string; statements: readonly string[] }[] = ${JSON.stringify(migrations, null, 2)};
`;
writeFileSync(join(root, "src/migrations.generated.ts"), out);
console.log(`Exported ${migrations.length} migration(s)`);
